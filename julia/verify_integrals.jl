# Closed forms used in Lemma 7.3.
include(joinpath(@__DIR__, "common.jl"))
for ε in (0.02, 0.05, 0.1, 0.134)
    x = range(0, 2π, length = 2_000_001)[1:end-1]; s = sin.(x); N = length(x)
    mh = sum(ε^2 ./ (s .^ 2 .+ ε^2)) / N
    mh2 = sum((ε^2 ./ (s .^ 2 .+ ε^2)) .^ 2) / N
    i1 = sum(1 ./ (s .^ 2 .+ ε^2)) / N
    i2 = sum(1 ./ (s .^ 2 .+ ε^2) .^ 2) / N
    check("mean ε²/(s²+ε²) = ε/√(1+ε²) (ε=$ε)", abs(mh - ε / sqrt(1 + ε^2)) < 1e-10)
    check("mean (ε²/(s²+ε²))² = ε(1+2ε²)/(2(1+ε²)^{3/2}) (ε=$ε)", abs(mh2 - ε * (1 + 2ε^2) / (2 * (1 + ε^2)^1.5)) < 1e-10)
    check("mean 1/(s²+ε²) = 1/(ε√(1+ε²)) (ε=$ε)", abs(i1 - 1 / (ε * sqrt(1 + ε^2))) < 1e-7 * i1)
    check("mean 1/(s²+ε²)² = (1+2ε²)/(2ε³(1+ε²)^{3/2}) (ε=$ε)", abs(i2 - (1 + 2ε^2) / (2ε^3 * (1 + ε^2)^1.5)) < 1e-7 * i2)
    check("ε(1+2ε²)/(2(1+ε²)^{3/2}) ≤ ε (ε=$ε)", (1 + 2ε^2) / (2 * (1 + ε^2)^1.5) <= 1)
end
